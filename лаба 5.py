# 4. ЕКОНОМІКА ТА КІНЕЦЬ ГРИ (Economy)
# ==========================================
class GameEconomy:  # #клас_що_відповідає_за_гроші_дні_та_умови_гри
    def __init__(self, starting_gold: int = 100, target_gold: int = 1000, max_days: int = 15):  # #конструктор_економіки
        self.gold = starting_gold  # #встановлюємо_початковий_капітал_золота
        self.target_gold = target_gold  # #встановлюємо_ціль_золота_для_перемоги
        self.max_days = max_days  # #встановлюємо_максимальну_кількість_днів
        self.current_day = 1  # #починаємо_рахунок_із_першого_дня

    def sell_potions(self, potion_name: str, quantity: int, price_dict: dict) -> int:  # #метод_продажу_зілля
        price = price_dict.get(potion_name, 10) * quantity  # #множимо_ціну_зілля_на_його_кількість
        self.gold += price  # #додаємо_зароблене_золото_до_балансу_гравця
        return price  # #повертаємо_суму_заробітку_за_продаж

    def check_game_status(self) -> str:  # #метод_перевірки_чи_гра_завершена
        if self.gold >= self.target_gold:  # #якщо_накопичено_достатньо_золота
            return "win"  # #сигнал_про_перемогу
        if self.current_day > self.max_days:  # #якщо_дні_вичерпано_а_ціль_не_досягнута
            return "lose"  # #сигнал_про_поразку
        return "continue"  # #гра_продовжується


