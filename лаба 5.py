class InventorySlot:  # #клас_що_описує_один_слот_інвентарю_з_предметами
    def __init__(self, item_name: str, quantity: int, max_stack: int):  # #конструктор_створення_слоту
        self.item_name = item_name  # #зберігаємо_назву_предмета_у_цьому_слоті
        self.quantity = quantity  # #зберігаємо_поточну_кількість_предметів
        self.max_stack = max_stack  # #зберігаємо_ліміт_стакування_для_цього_предмета

    def add(self, amount: int) -> int:  # #метод_додавання_предметів_у_слот
        space_left = self.max_stack - self.quantity  # #рахуємо_скільки_вільного_місця_залишилось_у_стаку
        if amount <= space_left:  # #якщо_кількість_повністю_поміщається_у_слот
            self.quantity += amount  # #збільшуємо_поточну_кількість_на_додану
            return 0  # #повертаємо_нуль_залишку_оскільки_все_помістилось
        else:
            self.quantity = self.max_stack  # #заповнюємо_слот_до_максимального_ліміту
            return amount - space_left  # #повертаємо_непоміщений_залишок_для_наступних_слотів

    def remove(self, amount: int) -> int:  # #метод_видалення_предметів_із_слоту
        if amount <= self.quantity:  # #якщо_в_слоті_достатньо_предметів_для_видалення
            self.quantity -= amount  # #зменшуємо_кількість_предметів
            return 0  # #повертаємо_нуль_залишку
        else:
            leftover = amount - self.quantity  # #обчислюємо_скільки_не_вистачило_видалити_з_цього_слоту
            self.quantity = 0  # #повністю_очищуємо_слот
            return leftover  # #повертаємо_залишок_який_треба_забрати_з_інших_слотів


class Inventory:  # #клас_що_управляє_усіма_слотами_інвентарю
    def __init__(self, max_slots: int, max_stack: int):  # #конструктор_головного_інвентарю
        self.max_slots = max_slots  # #встановлюємо_ліміт_кількості_слотів
        self.max_stack = max_stack  # #встановлюємо_ліміт_стаку_в_один_слот
        self.slots = []  # #створюємо_пустий_список_для_зберігання_слотів

    def add_item(self, item_name: str, quantity: int) -> None:  # #метод_додавання_предмета_в_інвентар
        remaining = quantity  # #зберігаємо_загальну_кількість_для_розподілу

        for slot in self.slots:  # #перебираємо_існуючі_слоти_в_інвентарі
            if slot.item_name == item_name and slot.quantity < self.max_stack:  # #якщо_знайшли_неповний_стак_цього_ж_предмета
                remaining = slot.add(remaining)  # #додаємо_в_нього_частину_або_все
                if remaining == 0:  # #якщо_все_успішно_розподілилось
                    return  # #виходимо_з_методу

        while remaining > 0:  # #якщо_залишилися_предмети_які_не_помістилися_в_існуючі_стаки
            if len(self.slots) >= self.max_slots:  # #перевіряємо_чи_не_закінчилися_вільні_слоти
                raise InventoryFullError(
                    "Інвентар переповнено! Немає вільних слотів.")  # #викликаємо_помилку_переповнення

            to_add = min(remaining, self.max_stack)  # #визначаємо_скільки_можна_покласти_в_новий_слот
            new_slot = InventorySlot(item_name, to_add, self.max_stack)  # #створюємо_новий_обєкт_слоту
            self.slots.append(new_slot)  # #додаємо_новий_слот_до_інвентарю
            remaining -= to_add  # #зменшуємо_нерозподілений_залишок

    def remove_item(self, item_name: str, quantity: int) -> bool:  # #метод_видалення_предметів_з_інвентарю
        total_available = sum(slot.quantity for slot in self.slots if
                              slot.item_name == item_name)  # #рахуємо_загальну_наявну_кількість_предмета
        if total_available < quantity:  # #якщо_предмета_загалом_менше_ніж_треба_видалити
            return False  # #повертаємо_хибу_і_скасовуємо_дію

        remaining_to_remove = quantity  # #зберігаємо_кількість_яку_треба_видалити
        for slot in self.slots[:]:  # #робимо_копію_списку_слотів_для_безпечного_перебору
            if slot.item_name == item_name:  # #якщо_знайшли_потрібний_предмет_у_слоті
                leftover = slot.remove(remaining_to_remove)  # #видаляємо_з_цього_слоту
                remaining_to_remove = leftover  # #оновлюємо_залишок_для_видалення
                if slot.quantity == 0:  # #якщо_після_видалення_слот_став_пуртим
                    self.slots.remove(slot)  # #видаляємо_цей_пустий_слот_з_інвентарю
                if remaining_to_remove == 0:  # #якщо_все_необхідне_успішно_видалили
                    break  # #перериваємо_цикл
        return True  # #повертаємо_успіх_видалення

    def get_count(self, item_name: str) -> int:  # #метод_підрахунку_кількості_певного_предмета
        return sum(
            slot.quantity for slot in self.slots if slot.item_name == item_name)  # #сумуємо_кількості_по_всіх_слотах


